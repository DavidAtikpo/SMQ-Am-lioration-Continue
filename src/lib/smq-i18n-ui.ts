export type SmqUiKey = keyof typeof SMQ_UI.fr;

export function getSmqUi(locale: SmqLocale) {
  return SMQ_UI[locale];
}

export function translateSmqStoredLabel(value: string, locale: SmqLocale): string {
  if (locale === "fr") return value;
  return SMQ_STORED_LABEL_EN[value] ?? value;
}

type RelativeDeadlineUi = {
  daysLate: string;
  today: string;
  inDays: string;
  daysShort: string;
};

export function formatRelativeDeadline(
  days: number | null | undefined,
  _locale: SmqLocale,
  ui: RelativeDeadlineUi,
): string {
  const d = days ?? 0;
  if (d < 0) return `${-d} ${ui.daysLate}`;
  if (d === 0) return ui.today;
  return `${ui.inDays} ${d} ${ui.daysShort}`;
}

